var net = null;
function initNet() {
  var cv = $('#net'), hero = $('#home'); if (!cv || !cv.getContext || !hero) return null;
  var ctx = cv.getContext('2d'); if (!ctx) return null;
  var W = 0, Hh = 0, lw = 0, nodes = [], raf = 0, vis = true, LINK = 130;
  var col = { a: '34,211,238', b: '129,140,248', m: '52,211,153', k: 1 }, mouse = { x: -9999, y: -9999, on: false };
  var reduced = window.matchMedia ? matchMedia('(prefers-reduced-motion: reduce)') : { matches: false };
  function readCol() { var cs = getComputedStyle(H); col = { a: cs.getPropertyValue('--net-a').trim() || col.a, b: cs.getPropertyValue('--net-b').trim() || col.b, m: cs.getPropertyValue('--net-m').trim() || col.m, k: parseFloat(cs.getPropertyValue('--net-alpha')) || 1 }; }
  function size(force) {
    var r = cv.getBoundingClientRect(), dpr = Math.min(window.devicePixelRatio || 1, 2), bw = Math.round(r.width * dpr), bh = Math.round(r.height * dpr);
    if (!force && bw === cv.width && bh === cv.height) return;
    // the bitmap always follows the element (no stretching); nodes are re-seeded only for big changes,
    // small ones (address bar, rotation of a few px) just rescale the existing constellation
    var reseed = force || !nodes.length || Math.abs(r.width - lw) >= 2 || Math.abs(r.height - Hh) >= 140;
    var sx = W ? r.width / W : 1, sy = Hh ? r.height / Hh : 1;
    W = r.width; Hh = r.height; lw = W;
    cv.width = bw; cv.height = bh; ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    if (!reseed) { nodes.forEach(function (p) { p.x *= sx; p.y *= sy; }); return; }
    var n = Math.max(26, Math.min(118, Math.round(W * Hh / 12500))); nodes = [];
    for (var i = 0; i < n; i++) nodes.push({ x: Math.random() * W, y: Math.random() * Hh, vx: (Math.random() - .5) * .42, vy: (Math.random() - .5) * .42, r: Math.random() * 1.4 + .7, c: Math.random() < .55 ? 0 : 1, h: Math.random() < .09 });
  }
  function frame(move) {
    ctx.clearRect(0, 0, W, Hh); var i, j, p, q, dx, dy, d2, d;
    if (move) { for (i = 0; i < nodes.length; i++) { p = nodes[i];
      if (mouse.on) { dx = p.x - mouse.x; dy = p.y - mouse.y; d2 = dx * dx + dy * dy; if (d2 < 12100 && d2 > 1) { d = Math.sqrt(d2); var f = (110 - d) / 110 * .05; p.vx += dx / d * f; p.vy += dy / d * f; } }
      var sp = Math.sqrt(p.vx * p.vx + p.vy * p.vy); if (sp > .9) { p.vx *= .9 / sp; p.vy *= .9 / sp; } else if (sp < .1) { p.vx += (Math.random() - .5) * .06; p.vy += (Math.random() - .5) * .06; }
      p.vx *= .996; p.vy *= .996; p.x += p.vx; p.y += p.vy;
      if (p.x < -12) p.x = W + 12; else if (p.x > W + 12) p.x = -12; if (p.y < -12) p.y = Hh + 12; else if (p.y > Hh + 12) p.y = -12; } }
    ctx.lineWidth = 1;
    for (i = 0; i < nodes.length; i++) { p = nodes[i]; for (j = i + 1; j < nodes.length; j++) { q = nodes[j]; dx = p.x - q.x; dy = p.y - q.y; d2 = dx * dx + dy * dy;
      if (d2 < LINK * LINK) { var al = (1 - Math.sqrt(d2) / LINK) * .42 * col.k; ctx.strokeStyle = 'rgba(' + (p.c ? col.b : col.a) + ',' + al.toFixed(3) + ')'; ctx.beginPath(); ctx.moveTo(p.x, p.y); ctx.lineTo(q.x, q.y); ctx.stroke(); } } }
    if (mouse.on) { for (i = 0; i < nodes.length; i++) { p = nodes[i]; dx = p.x - mouse.x; dy = p.y - mouse.y; d = Math.sqrt(dx * dx + dy * dy);
      if (d < 190) { ctx.strokeStyle = 'rgba(' + col.m + ',' + ((1 - d / 190) * .5 * col.k).toFixed(3) + ')'; ctx.beginPath(); ctx.moveTo(p.x, p.y); ctx.lineTo(mouse.x, mouse.y); ctx.stroke(); } } }
    for (i = 0; i < nodes.length; i++) { p = nodes[i]; var c = p.c ? col.b : col.a;
      if (p.h) { ctx.fillStyle = 'rgba(' + c + ',' + (.16 * col.k).toFixed(3) + ')'; ctx.beginPath(); ctx.arc(p.x, p.y, 7.5, 0, 6.2832); ctx.fill(); }
      ctx.fillStyle = 'rgba(' + c + ',' + (.9 * col.k).toFixed(3) + ')'; ctx.beginPath(); ctx.arc(p.x, p.y, p.h ? 2.5 : p.r, 0, 6.2832); ctx.fill(); }
  }
  function loop() { frame(true); raf = requestAnimationFrame(loop); }
  function start() { if (raf || reduced.matches || !vis || DOC.hidden) return; raf = requestAnimationFrame(loop); }
  function stop() { if (raf) cancelAnimationFrame(raf); raf = 0; }
  readCol(); size(true); frame(false); start();
  var rt = 0, onR = function () { clearTimeout(rt); rt = setTimeout(function () { size(false); if (!raf) frame(false); }, 160); };
  if ('ResizeObserver' in window) new ResizeObserver(onR).observe(hero); else window.addEventListener('resize', onR);
  DOC.addEventListener('visibilitychange', function () { if (DOC.hidden) stop(); else start(); });
  if (HAS_IO) new IntersectionObserver(function (es) { vis = es[0].isIntersecting; if (vis) start(); else stop(); }).observe(hero);
  hero.addEventListener('pointermove', function (e) { if (e.pointerType === 'touch') return; var r = cv.getBoundingClientRect(); mouse.x = e.clientX - r.left; mouse.y = e.clientY - r.top; mouse.on = true; if (!raf) frame(false); });
  hero.addEventListener('pointerleave', function () { mouse.on = false; if (!raf) frame(false); });
  var onRM = function () { if (reduced.matches) { stop(); frame(false); } else start(); };
  if (reduced.addEventListener) reduced.addEventListener('change', onRM); else if (reduced.addListener) reduced.addListener(onRM);
  return { recolor: function () { readCol(); if (!raf) frame(false); } };
}

